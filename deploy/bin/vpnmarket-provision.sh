#!/usr/bin/env bash
# راه‌اندازی تعاملی Traefik + DB مشترک + وب pickup + ربات‌های تلگرام (Docker)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# shellcheck source=lib/instance-compose.sh
source "$ROOT/deploy/bin/lib/instance-compose.sh"
PROVISION_DIR="$ROOT/deploy/.provision"
CLUSTER_ENV="$PROVISION_DIR/cluster.env"
INSTANCES_DIR="$ROOT/deploy/instances"
TRAEFIK_DIR="$ROOT/deploy/traefik"

# --- helpers ---
info()  { printf '\033[1;36m→\033[0m %s\n' "$*"; }
ok()    { printf '\033[1;32m✓\033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m!\033[0m %s\n' "$*"; }
err()   { printf '\033[1;31m✗\033[0m %s\n' "$*" >&2; }

prompt() {
  local label="$1" default="${2:-}" value=""
  if [ -n "$default" ]; then
    read -r -p "$label [$default]: " value
    value="${value:-$default}"
  else
    read -r -p "$label: " value
  fi
  printf '%s' "$value"
}

prompt_secret() {
  local label="$1" default="${2:-}" value=""
  if [ -n "$default" ]; then
    read -r -s -p "$label [$default] (Enter=همان): " value
    echo ""
    value="${value:-$default}"
  else
    read -r -s -p "$label: " value
    echo ""
  fi
  printf '%s' "$value"
}

gen_password() {
  openssl rand -base64 24 | tr -d '/+=' | head -c 32
}

gen_app_key() {
  printf 'base64:%s' "$(openssl rand -base64 32)"
}

docker_net_exists() {
  docker network inspect "$1" >/dev/null 2>&1
}

ensure_proxy_network() {
  if docker_net_exists proxy; then
    ok "شبکه proxy موجود است"
    return 0
  fi
  docker network create proxy >/dev/null
  ok "شبکه proxy ساخته شد"
}

container_running() {
  docker ps --format '{{.Names}}' | grep -qx "$1"
}

load_cluster() {
  # shellcheck disable=SC1090
  [ -f "$CLUSTER_ENV" ] && source "$CLUSTER_ENV"
  traefik_running && INFRA_TRAEFIK=1
  container_running vpnmarket_shared_mysql && INFRA_SHARED_DB=1
  if [ -n "${PICKUP_DOMAIN:-}" ] && [ -f "$INSTANCES_DIR/$PICKUP_DOMAIN/.env" ]; then
    INFRA_PICKUP=1
  fi
}

traefik_running() {
  docker ps --filter "name=traefik" --filter "status=running" -q 2>/dev/null | grep -q .
}

save_cluster() {
  mkdir -p "$PROVISION_DIR"
  umask 077
  cat >"$CLUSTER_ENV" <<EOF
# Generated by vpnmarket-provision.sh — $(date -Iseconds)
ACME_EMAIL=${ACME_EMAIL:-}
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD:-}
DB_USERNAME=${DB_USERNAME:-vpnmarket}
DB_PASSWORD=${DB_PASSWORD:-}
DB_DATABASE=${DB_DATABASE:-vpnmarket_shared}
SHARED_DATA_NETWORK=${SHARED_DATA_NETWORK:-vpnmarket_shared_data}
TRAEFIK_NETWORK=${TRAEFIK_NETWORK:-proxy}
TRAEFIK_CERT_RESOLVER=${TRAEFIK_CERT_RESOLVER:-letsencrypt}
PICKUP_DOMAIN=${PICKUP_DOMAIN:-bale.cyou}
IRAN_SERVICE_SHARE_URL=${IRAN_SERVICE_SHARE_URL:-https://bale.cyou}
APP_IMAGE=${APP_IMAGE:-vpnmarket/app:latest}
INFRA_TRAEFIK=${INFRA_TRAEFIK:-0}
INFRA_SHARED_DB=${INFRA_SHARED_DB:-0}
INFRA_PICKUP=${INFRA_PICKUP:-0}
EOF
  chmod 600 "$CLUSTER_ENV"
}

normalize_domain() {
  echo "$1" | tr '[:upper:]' '[:lower:]'
}

domain_slug() {
  echo "$1" | tr '[:upper:]' '[:lower:]' | sed 's/[^a-z0-9]/_/g' | sed 's/__*/_/g' | sed 's/^_//;s/_$//'
}

instance_project_name() {
  echo "vpnmarket_$(domain_slug "$1")"
}

instance_env_file() {
  local dest="$1"
  local f="$dest/.env"
  [ -f "$f" ] || { err "فایل .env نیست: $f"; return 1; }
  printf '%s/.env' "$(cd "$dest" && pwd)"
}

app_image_from_env() {
  local env_file="$1" line
  line="$(grep -E '^APP_IMAGE=' "$env_file" | tail -1 || true)"
  line="${line#APP_IMAGE=}"
  line="${line%\"}"
  line="${line#\"}"
  line="${line:-vpnmarket/app:latest}"
  if docker image inspect "$line" >/dev/null 2>&1; then
    printf '%s' "$line"
  elif docker image inspect "vpnmarket/app:latest" >/dev/null 2>&1; then
    printf '%s' "vpnmarket/app:latest"
  else
    printf '%s' "$line"
  fi
}

build_app_image() {
  local env_file="$1" image
  image="$(app_image_from_env "$env_file")"
  if [ ! -f "$ROOT/Dockerfile" ]; then
    err "Dockerfile در $ROOT نیست"
    return 1
  fi
  info "ساخت image محلی از $ROOT/Dockerfile → $image (چند دقیقه)"
  if ! docker build -t "$image" -f "$ROOT/Dockerfile" "$ROOT"; then
    err "docker build ناموفق بود"
    return 1
  fi
  docker image inspect "$image" >/dev/null || { err "image بعد از build پیدا نشد: $image"; return 1; }
  ok "image آماده: $image"
}

ensure_app_image() {
  build_app_image "$1"
}

compose_bot() {
  local dest="$1"
  shift
  INSTANCE_ENV_FILE="$(instance_env_file "$dest")"
  export INSTANCE_ENV_FILE ENV_FILE="$INSTANCE_ENV_FILE"
  set -a
  # shellcheck disable=SC1090
  source "$INSTANCE_ENV_FILE"
  set +a
  if [ "${1:-}" = "up" ]; then
    ensure_app_image "$INSTANCE_ENV_FILE"
  fi
  docker compose --project-directory "$ROOT" \
    -f "$ROOT/docker-compose.yml" \
    -f "$ROOT/deploy/docker-compose.no-local-db.yml" \
    -f "$ROOT/deploy/docker-compose.instance-env.yml" \
    -f "$ROOT/deploy/docker-compose.build-root.yml" \
    -f "$ROOT/docker-compose.traefik.yml" \
    -f "$dest/docker-compose.yml" \
    --env-file "$INSTANCE_ENV_FILE" \
    -p "$(grep '^COMPOSE_PROJECT_NAME=' "$INSTANCE_ENV_FILE" | cut -d= -f2-)" \
    "$@"
}

compose_pickup() {
  local dest="$1"
  shift
  INSTANCE_ENV_FILE="$(instance_env_file "$dest")"
  export INSTANCE_ENV_FILE ENV_FILE="$INSTANCE_ENV_FILE"
  set -a
  # shellcheck disable=SC1090
  source "$INSTANCE_ENV_FILE"
  set +a
  if [ "${1:-}" = "up" ]; then
    ensure_app_image "$INSTANCE_ENV_FILE"
  fi
  docker compose --project-directory "$ROOT" \
    -f "$ROOT/docker-compose.yml" \
    -f "$ROOT/deploy/docker-compose.no-local-db.yml" \
    -f "$ROOT/deploy/docker-compose.instance-env.yml" \
    -f "$ROOT/deploy/docker-compose.build-root.yml" \
    -f "$ROOT/deploy/docker-compose.pickup-only.yml" \
    -f "$ROOT/docker-compose.traefik.yml" \
    -f "$dest/docker-compose.yml" \
    --env-file "$INSTANCE_ENV_FILE" \
    -p "$(grep '^COMPOSE_PROJECT_NAME=' "$INSTANCE_ENV_FILE" | cut -d= -f2-)" \
    "$@"
}

wait_container_up() {
  local container="$1" path="${2:-/up}" max="${3:-40}" i=0
  info "بررسی اپ داخل کانتینر $container ..."
  while [ "$i" -lt "$max" ]; do
    if docker exec "$container" curl -fsS -o /dev/null "http://127.0.0.1${path}" 2>/dev/null; then
      ok "اپ داخل کانتینر پاسخ داد (${path})"
      return 0
    fi
    i=$((i + 1))
    sleep 2
  done
  warn "اپ داخل کانتینر هنوز پاسخ نمی‌دهد — لاگ: docker logs $container"
  return 1
}

wait_url() {
  local url="$1" max="${2:-40}" i=0
  info "بررسی از بیرون $url (DNS + SSL؛ ممکن است ۱–۲ دقیقه طول بکشد) ..."
  while [ "$i" -lt "$max" ]; do
    if curl -fsS -k -o /dev/null --connect-timeout 5 "$url" 2>/dev/null; then
      ok "دسترسی بیرونی OK: $url"
      return 0
    fi
    i=$((i + 1))
    sleep 3
  done
  warn "هنوز $url از بیرون جواب نمی‌دهد — DNS را به IP سرور بزنید و Traefik را یک‌بار restart کنید"
  return 1
}

ensure_traefik() {
  if traefik_running; then
    ok "Traefik در حال اجراست"
    INFRA_TRAEFIK=1
    return 0
  fi

  info "راه‌اندازی Traefik (پورت 80/443)"
  if [ -z "${ACME_EMAIL:-}" ]; then
    ACME_EMAIL="$(prompt "ایمیل Let's Encrypt (ACME)" "")"
  fi
  mkdir -p "$TRAEFIK_DIR"
  printf 'ACME_EMAIL=%s\n' "$ACME_EMAIL" >"$TRAEFIK_DIR/.env"
  touch "$TRAEFIK_DIR/acme.json"
  chmod 600 "$TRAEFIK_DIR/acme.json"

  ensure_proxy_network

  (cd "$TRAEFIK_DIR" && docker compose up -d)
  sleep 3
  INFRA_TRAEFIK=1
  ok "Traefik بالا آمد"
  warn "اگر SSL قبلاً کار نمی‌کرد: cd $TRAEFIK_DIR && docker compose up -d --force-recreate"
}

require_db_credentials() {
  load_cluster
  if [ -z "${DB_PASSWORD:-}" ] || [ -z "${DB_USERNAME:-}" ] || [ -z "${DB_DATABASE:-}" ]; then
    err "رمز/کاربر DB در deploy/.provision/cluster.env نیست. یک‌بار گزینه ۴ (زیرساخت) را بزنید یا cluster.env را پر کنید."
    return 1
  fi
}

ensure_instance_compose_vars() {
  local dest="$1" domain="$2"
  local envf="${dest}/.env" project key val
  project="$(instance_project_name "$domain")"
  [ -f "$envf" ] || return 0
  for key in COMPOSE_PROJECT_NAME TRAEFIK_ROUTER_NAME; do
    val="$project"
    if grep -q "^${key}=" "$envf" 2>/dev/null; then
      sed -i "s|^${key}=.*|${key}=${val}|" "$envf"
    else
      echo "${key}=${val}" >>"$envf"
    fi
  done
  domain="$(normalize_domain "$domain")"
  if grep -q '^APP_DOMAIN=' "$envf" 2>/dev/null; then
    sed -i "s|^APP_DOMAIN=.*|APP_DOMAIN=${domain}|" "$envf"
  else
    echo "APP_DOMAIN=${domain}" >>"$envf"
  fi
  if grep -q '^APP_URL=' "$envf" 2>/dev/null; then
    sed -i "s|^APP_URL=.*|APP_URL=https://${domain}|" "$envf"
  fi
  if ! grep -q '^APP_IMAGE=' "$envf" 2>/dev/null; then
    echo "APP_IMAGE=vpnmarket/app:latest" >>"$envf"
  fi
}

repair_instance_db_env() {
  local dest="$1" domain="${2:-}"
  local envf="${dest}/.env"
  require_db_credentials || return 1
  [ -f "$envf" ] || return 0
  [ -n "$domain" ] || domain="$(basename "$dest")"

  warn "همگام‌سازی DB_* در $envf با cluster.env"
  grep -v -E '^(DB_CONNECTION|DB_HOST|DB_PORT|DB_DATABASE|DB_USERNAME|DB_PASSWORD|MYSQL_ROOT_PASSWORD)=' "$envf" >"${envf}.tmp"
  {
    echo 'DB_CONNECTION=mysql'
    echo 'DB_HOST=mysql'
    echo 'DB_PORT=3306'
    printf 'DB_DATABASE=%s\n' "$DB_DATABASE"
    printf 'DB_USERNAME=%s\n' "$DB_USERNAME"
    printf 'DB_PASSWORD=%s\n' "$DB_PASSWORD"
    printf 'MYSQL_ROOT_PASSWORD=%s\n' "$MYSQL_ROOT_PASSWORD"
  } >>"${envf}.tmp"
  mv "${envf}.tmp" "$envf"
  chmod 640 "$envf"
  ensure_instance_compose_vars "$dest" "$domain"
  ok "DB_USERNAME=${DB_USERNAME} DB_DATABASE=${DB_DATABASE}"
}

wait_for_container_ready() {
  local container="$1" max="${2:-60}" i=0
  while [ "$i" -lt "$max" ]; do
    if docker exec "$container" test -f /var/www/html/.env 2>/dev/null \
      && docker exec "$container" pgrep -x supervisord >/dev/null 2>&1; then
      return 0
    fi
    i=$((i + 1))
    sleep 2
  done
  return 1
}

sync_mysql_app_user() {
  require_db_credentials || return 1
  container_running vpnmarket_shared_mysql || return 0
  info "همگام‌سازی کاربر MySQL (${DB_USERNAME}) با cluster.env"
  docker exec vpnmarket_shared_mysql mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
ALTER USER '${DB_USERNAME}'@'%' IDENTIFIED BY '${DB_PASSWORD}';
FLUSH PRIVILEGES;
EOSQL
}

run_instance_migrate() {
  local dest="$1" container="$2"
  clear_instance_config_cache "$container"
  sleep 2
  if docker exec "$container" php artisan migrate --force --no-interaction; then
    ok "migrate انجام شد"
    return 0
  fi
  warn "migrate ناموفق — بررسی:"
  docker exec "$container" grep -E '^DB_(USERNAME|PASSWORD|DATABASE)=' /var/www/html/.env 2>/dev/null || true
  return 1
}

clear_instance_config_cache() {
  local container="$1"
  [ -n "$container" ] || return 0
  docker exec "$container" rm -f /var/www/html/bootstrap/cache/config.php 2>/dev/null || true
  docker exec "$container" php artisan config:clear --no-interaction 2>/dev/null || true
}

ensure_shared_db() {
  if container_running vpnmarket_shared_mysql; then
    ok "MySQL مشترک در حال اجراست"
    INFRA_SHARED_DB=1
    load_cluster
    return 0
  fi

  info "راه‌اندازی MySQL + Redis مشترک"
  if [ -z "${MYSQL_ROOT_PASSWORD:-}" ]; then
    MYSQL_ROOT_PASSWORD="$(gen_password)"
    ok "رمز root MySQL ساخته شد (در cluster.env ذخیره می‌شود)"
  fi
  if [ -z "${DB_PASSWORD:-}" ]; then
    DB_PASSWORD="$(gen_password)"
    ok "رمز کاربر DB ساخته شد"
  fi
  DB_USERNAME="${DB_USERNAME:-vpnmarket}"
  DB_DATABASE="${DB_DATABASE:-vpnmarket_shared}"
  SHARED_DATA_NETWORK="${SHARED_DATA_NETWORK:-vpnmarket_shared_data}"

  export MYSQL_ROOT_PASSWORD DB_USERNAME DB_PASSWORD

  (cd "$ROOT" && docker compose -f docker-compose.shared-db.yml up -d)

  info "منتظر MySQL ..."
  local i=0
  while [ "$i" -lt 60 ]; do
    if docker exec vpnmarket_shared_mysql mysqladmin ping -h127.0.0.1 -uroot -p"${MYSQL_ROOT_PASSWORD}" --silent 2>/dev/null; then
      break
    fi
    i=$((i + 1))
    sleep 2
  done

  docker exec -i vpnmarket_shared_mysql mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS \`${DB_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USERNAME}'@'%' IDENTIFIED BY '${DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${DB_DATABASE}\`.* TO '${DB_USERNAME}'@'%';
FLUSH PRIVILEGES;
EOSQL

  INFRA_SHARED_DB=1
  save_cluster
  ok "MySQL/Redis مشترک آماده است"
}

