#!/usr/bin/env bash
# راه‌اندازی تعاملی Traefik + DB مشترک + وب pickup + ربات‌های تلگرام (Docker)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
PROVISION_DIR="$ROOT/deploy/.provision"
CLUSTER_ENV="$PROVISION_DIR/cluster.env"
INSTANCES_DIR="$ROOT/deploy/instances"
TRAEFIK_DIR="$ROOT/deploy/traefik"

# --- helpers ---
info()  { printf '\033[1;36m→\033[0m %s\n' "$*"; }
ok()    { printf '\033[1;32m✓\033[0m %s\n' "$*"; }
warn()  { printf '\033[1;33m!\033[0m %s\n' "$*"; }
err()   { printf '\033[1;31m✗\033[0m %s\n' "$*" >&2; }

prompt() {
  local label="$1" default="${2:-}" value=""
  if [ -n "$default" ]; then
    read -r -p "$label [$default]: " value
    value="${value:-$default}"
  else
    read -r -p "$label: " value
  fi
  printf '%s' "$value"
}

prompt_secret() {
  local label="$1" default="${2:-}" value=""
  if [ -n "$default" ]; then
    read -r -s -p "$label [$default] (Enter=همان): " value
    echo ""
    value="${value:-$default}"
  else
    read -r -s -p "$label: " value
    echo ""
  fi
  printf '%s' "$value"
}

gen_password() {
  openssl rand -base64 24 | tr -d '/+=' | head -c 32
}

gen_app_key() {
  printf 'base64:%s' "$(openssl rand -base64 32)"
}

docker_net_exists() {
  docker network inspect "$1" >/dev/null 2>&1
}

container_running() {
  docker ps --format '{{.Names}}' | grep -qx "$1"
}

load_cluster() {
  # shellcheck disable=SC1090
  [ -f "$CLUSTER_ENV" ] && source "$CLUSTER_ENV"
  traefik_running && INFRA_TRAEFIK=1
  container_running vpnmarket_shared_mysql && INFRA_SHARED_DB=1
  if [ -n "${PICKUP_DOMAIN:-}" ] && [ -f "$INSTANCES_DIR/$PICKUP_DOMAIN/.env" ]; then
    INFRA_PICKUP=1
  fi
}

traefik_running() {
  docker ps --filter "name=traefik" --filter "status=running" -q 2>/dev/null | grep -q .
}

save_cluster() {
  mkdir -p "$PROVISION_DIR"
  umask 077
  cat >"$CLUSTER_ENV" <<EOF
# Generated by vpnmarket-provision.sh — $(date -Iseconds)
ACME_EMAIL=${ACME_EMAIL:-}
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD:-}
DB_USERNAME=${DB_USERNAME:-vpnmarket}
DB_PASSWORD=${DB_PASSWORD:-}
DB_DATABASE=${DB_DATABASE:-vpnmarket_shared}
SHARED_DATA_NETWORK=${SHARED_DATA_NETWORK:-vpnmarket_shared_data}
TRAEFIK_NETWORK=${TRAEFIK_NETWORK:-proxy}
TRAEFIK_CERT_RESOLVER=${TRAEFIK_CERT_RESOLVER:-letsencrypt}
PICKUP_DOMAIN=${PICKUP_DOMAIN:-bale.cyou}
IRAN_SERVICE_SHARE_URL=${IRAN_SERVICE_SHARE_URL:-https://bale.cyou}
APP_IMAGE=${APP_IMAGE:-vpnmarket/app:latest}
INFRA_TRAEFIK=${INFRA_TRAEFIK:-0}
INFRA_SHARED_DB=${INFRA_SHARED_DB:-0}
INFRA_PICKUP=${INFRA_PICKUP:-0}
EOF
  chmod 600 "$CLUSTER_ENV"
}

instance_project_name() {
  local domain="$1"
  echo "vpnmarket_${domain//./_}"
}

compose_bot() {
  local dest="$1"
  shift
  docker compose \
    -f "$ROOT/docker-compose.yml" \
    -f "$ROOT/deploy/docker-compose.no-local-db.yml" \
    -f "$ROOT/docker-compose.traefik.yml" \
    -f "$dest/docker-compose.yml" \
    --env-file "$dest/.env" \
    -p "$(grep '^COMPOSE_PROJECT_NAME=' "$dest/.env" | cut -d= -f2-)" \
    "$@"
}

compose_pickup() {
  local dest="$1"
  shift
  docker compose \
    -f "$ROOT/docker-compose.yml" \
    -f "$ROOT/deploy/docker-compose.no-local-db.yml" \
    -f "$ROOT/deploy/docker-compose.pickup-only.yml" \
    -f "$ROOT/docker-compose.traefik.yml" \
    -f "$dest/docker-compose.yml" \
    --env-file "$dest/.env" \
    -p "$(grep '^COMPOSE_PROJECT_NAME=' "$dest/.env" | cut -d= -f2-)" \
    "$@"
}

wait_url() {
  local url="$1" max="${2:-90}" i=0
  info "منتظر آماده‌شدن $url ..."
  while [ "$i" -lt "$max" ]; do
    if curl -fsS -k -o /dev/null "$url" 2>/dev/null; then
      return 0
    fi
    i=$((i + 1))
    sleep 3
  done
  return 1
}

ensure_traefik() {
  if traefik_running; then
    ok "Traefik در حال اجراست"
    INFRA_TRAEFIK=1
    return 0
  fi

  info "راه‌اندازی Traefik (پورت 80/443)"
  if [ -z "${ACME_EMAIL:-}" ]; then
    ACME_EMAIL="$(prompt "ایمیل Let's Encrypt (ACME)" "")"
  fi
  mkdir -p "$TRAEFIK_DIR"
  printf 'ACME_EMAIL=%s\n' "$ACME_EMAIL" >"$TRAEFIK_DIR/.env"
  touch "$TRAEFIK_DIR/acme.json"
  chmod 600 "$TRAEFIK_DIR/acme.json"

  if ! docker_net_exists proxy; then
    docker network create proxy >/dev/null
  fi

  (cd "$TRAEFIK_DIR" && docker compose up -d)
  sleep 3
  INFRA_TRAEFIK=1
  ok "Traefik بالا آمد"
}

ensure_shared_db() {
  if container_running vpnmarket_shared_mysql; then
    ok "MySQL مشترک در حال اجراست"
    INFRA_SHARED_DB=1
    return 0
  fi

  info "راه‌اندازی MySQL + Redis مشترک"
  if [ -z "${MYSQL_ROOT_PASSWORD:-}" ]; then
    MYSQL_ROOT_PASSWORD="$(gen_password)"
    ok "رمز root MySQL ساخته شد (در cluster.env ذخیره می‌شود)"
  fi
  if [ -z "${DB_PASSWORD:-}" ]; then
    DB_PASSWORD="$(gen_password)"
    ok "رمز کاربر DB ساخته شد"
  fi
  DB_USERNAME="${DB_USERNAME:-vpnmarket}"
  DB_DATABASE="${DB_DATABASE:-vpnmarket_shared}"
  SHARED_DATA_NETWORK="${SHARED_DATA_NETWORK:-vpnmarket_shared_data}"

  export MYSQL_ROOT_PASSWORD DB_USERNAME DB_PASSWORD

  (cd "$ROOT" && docker compose -f docker-compose.shared-db.yml up -d)

  info "منتظر MySQL ..."
  local i=0
  while [ "$i" -lt 60 ]; do
    if docker exec vpnmarket_shared_mysql mysqladmin ping -h127.0.0.1 -uroot -p"${MYSQL_ROOT_PASSWORD}" --silent 2>/dev/null; then
      break
    fi
    i=$((i + 1))
    sleep 2
  done

  docker exec -i vpnmarket_shared_mysql mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<EOSQL
CREATE DATABASE IF NOT EXISTS \`${DB_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USERNAME}'@'%' IDENTIFIED BY '${DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${DB_DATABASE}\`.* TO '${DB_USERNAME}'@'%';
FLUSH PRIVILEGES;
EOSQL

  INFRA_SHARED_DB=1
  ok "MySQL/Redis مشترک آماده است"
}

write_bot_env() {
  local dest="$1" domain="$2" project="$3" instance_id="$4" app_name="$5" app_key="$6"
  cat >"$dest/.env" <<EOF
COMPOSE_PROJECT_NAME=${project}
APP_IMAGE=${APP_IMAGE:-vpnmarket/app:latest}

APP_INSTANCE_ID=${instance_id}
APP_NAME="${app_name}"
APP_ENV=production
APP_KEY=${app_key}
APP_DEBUG=false
APP_URL=https://${domain}

APP_DOMAIN=${domain}
TRAEFIK_ROUTER_NAME=${project}
TRAEFIK_CERT_RESOLVER=${TRAEFIK_CERT_RESOLVER:-letsencrypt}
TRAEFIK_NETWORK=${TRAEFIK_NETWORK:-proxy}

DB_CONNECTION=mysql
DB_HOST=mysql
DB_PORT=3306
DB_DATABASE=${DB_DATABASE}
DB_USERNAME=${DB_USERNAME}
DB_PASSWORD=${DB_PASSWORD}
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD}
SHARED_DATA_NETWORK=${SHARED_DATA_NETWORK}

REDIS_CLIENT=phpredis
REDIS_HOST=redis
REDIS_PASSWORD=null
REDIS_PORT=6379
REDIS_QUEUE_RETRY_AFTER=300

QUEUE_CONNECTION=redis
CACHE_STORE=redis
SESSION_DRIVER=database

LOG_CHANNEL=stack
LOG_LEVEL=info

APP_SHARE_PICKUP_ONLY=false
IRAN_SERVICE_SHARE_URL=${IRAN_SERVICE_SHARE_URL}
RUN_MIGRATIONS=true
WAIT_FOR_DB=true
EOF
  chmod 600 "$dest/.env"
}

write_pickup_env() {
  local dest="$1" domain="$2" project="$3" app_key="$4"
  cat >"$dest/.env" <<EOF
COMPOSE_PROJECT_NAME=${project}
APP_IMAGE=${APP_IMAGE:-vpnmarket/app:latest}

APP_INSTANCE_ID=pickup
APP_NAME="دریافت اشتراک"
APP_ENV=production
APP_KEY=${app_key}
APP_DEBUG=false
APP_URL=https://${domain}

APP_SHARE_PICKUP_ONLY=true
APP_DOMAIN=${domain}
TRAEFIK_ROUTER_NAME=${project}
TRAEFIK_CERT_RESOLVER=${TRAEFIK_CERT_RESOLVER:-letsencrypt}
TRAEFIK_NETWORK=${TRAEFIK_NETWORK:-proxy}

DB_CONNECTION=mysql
DB_HOST=mysql
DB_PORT=3306
DB_DATABASE=${DB_DATABASE}
DB_USERNAME=${DB_USERNAME}
DB_PASSWORD=${DB_PASSWORD}
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD}
SHARED_DATA_NETWORK=${SHARED_DATA_NETWORK}

REDIS_HOST=redis
QUEUE_CONNECTION=sync
CACHE_STORE=file
SESSION_DRIVER=file

RUN_MIGRATIONS=false
WAIT_FOR_DB=true
EOF
  chmod 600 "$dest/.env"
}

bootstrap_bot_container() {
  local dest="$1" domain="$2" token="$3" admin_email="$4" admin_pass="$5" admin_chat="$6"

  info "ساخت و اجرای کانتینرهای ربات ..."
  compose_bot "$dest" up -d --build

  if ! wait_url "https://${domain}/up" 120; then
    warn "health check از بیرون ناموفق — ادامه با docker exec ..."
  fi

  info "Seed پیام‌های ربات و bootstrap ..."
  compose_bot "$dest" exec -T web php artisan db:seed --class=BotMessageSeeder --force --no-interaction || true

  local provision_args=(--no-interaction)
  [ -n "$token" ] && provision_args+=(--token="$token")
  [ -n "$admin_email" ] && provision_args+=(--admin-email="$admin_email")
  [ -n "$admin_pass" ] && provision_args+=(--admin-password="$admin_pass")
  [ -n "$admin_chat" ] && provision_args+=(--telegram-admin-chat-id="$admin_chat")
  compose_bot "$dest" exec -T web php artisan vpnmarket:provision-instance "${provision_args[@]}"

  if [ -n "$token" ]; then
    info "ثبت webhook تلگرام ..."
    compose_bot "$dest" exec -T web php artisan telegram:set-webhook --no-interaction || warn "set-webhook خطا داد — بعداً دستی امتحان کنید"
  fi

  compose_bot "$dest" exec -T web php artisan config:clear --no-interaction || true
  compose_bot "$dest" exec -T web php artisan cache:clear --no-interaction || true
}

provision_pickup_site() {
  local domain="${1:-${PICKUP_DOMAIN:-bale.cyou}}"
  local dest="$INSTANCES_DIR/$domain"
  local project
  project="$(instance_project_name "$domain")"

  if [ -f "$dest/.env" ]; then
    err "وب pickup قبلاً وجود دارد: $dest"
    return 1
  fi

  mkdir -p "$dest"
  cp "$ROOT/deploy/instances/_template.pickup/docker-compose.yml" "$dest/docker-compose.yml"

  local app_key
  app_key="$(gen_app_key)"
  write_pickup_env "$dest" "$domain" "$project" "$app_key"

  info "اجرای وب pickup ($domain) ..."
  compose_pickup "$dest" up -d --build

  wait_url "https://${domain}/up" 90 || warn "health pickup از HTTPS چک نشد"

  INFRA_PICKUP=1
  PICKUP_DOMAIN="$domain"
  IRAN_SERVICE_SHARE_URL="https://${domain}"
  ok "وب pickup: https://${domain}"
}

provision_bot_instance() {
  local domain="$1"
  local dest="$INSTANCES_DIR/$domain"
  local project instance_id app_name app_key

  if [ -f "$dest/.env" ]; then
    err "این دامنه قبلاً ثبت شده: $dest"
    return 1
  fi

  project="$(instance_project_name "$domain")"
  instance_id="$(prompt "APP_INSTANCE_ID (یکتا در DB)" "$project")"
  app_name="$(prompt "نام نمایشی ربات (APP_NAME)" "VPNMarket")"
  app_key="$(gen_app_key)"

  mkdir -p "$dest"
  cp "$ROOT/deploy/instances/_template/docker-compose.yml" "$dest/docker-compose.yml"
  write_bot_env "$dest" "$domain" "$project" "$instance_id" "$app_name" "$app_key"

  local token admin_email admin_pass admin_chat
  token="$(prompt_secret "توکن ربات تلگرام (BotFather)" "")"
  admin_email="$(prompt "ایمیل ادمین پنل Filament" "admin@${domain}")"
  admin_pass="$(prompt_secret "رمز ادمین پنل" "$(gen_password)")"
  admin_chat="$(prompt "Chat ID ادمین تلگرام (اختیاری، Enter=رد)" "")"

  bootstrap_bot_container "$dest" "$domain" "$token" "$admin_email" "$admin_pass" "$admin_chat"

  ok "ربات آماده است"
  echo ""
  echo "  دامنه:        https://${domain}"
  echo "  پنل ادمین:   https://${domain}/admin"
  echo "  وب‌هوک:       https://${domain}/webhooks/telegram"
  echo "  ادمین:        ${admin_email}"
  echo "  پروژه Docker: ${project}"
  echo "  مسیر:         ${dest}"
}

show_status() {
  echo ""
  info "وضعیت زیرساخت:"
  docker ps --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}' | grep -E 'traefik|vpnmarket|mysql|redis' || true
  echo ""
  if [ -d "$INSTANCES_DIR" ]; then
    info "نمونه‌های ثبت‌شده:"
    for d in "$INSTANCES_DIR"/*/; do
      [ -d "$d" ] || continue
      base="$(basename "$d")"
      case "$base" in _template*) continue ;; esac
      echo "  - $base"
    done
  fi
  [ -f "$CLUSTER_ENV" ] && echo "" && info "تنظیمات خوشه: $CLUSTER_ENV"
}

ensure_prerequisites() {
  command -v docker >/dev/null || { err "docker نصب نیست"; exit 1; }
  docker compose version >/dev/null 2>&1 || { err "docker compose v2 لازم است"; exit 1; }
  command -v openssl >/dev/null || { err "openssl لازم است"; exit 1; }
  command -v curl >/dev/null || { err "curl لازم است"; exit 1; }
}

# --- main ---
ensure_prerequisites
load_cluster

echo ""
echo "╔══════════════════════════════════════════════╗"
echo "║   VPNMarket — نصب/افزودن Docker (تعاملی)     ║"
echo "╚══════════════════════════════════════════════╝"
echo ""

if [ -f "$CLUSTER_ENV" ]; then
  ok "تنظیمات خوشه از $CLUSTER_ENV خوانده شد"
else
  warn "اولین اجرا — زیرساخت مشترک ساخته می‌شود"
fi

echo ""
echo "  1) راه‌اندازی کامل سرور (Traefik + DB + وب کد ۵رقمی + یک ربات)"
echo "  2) فقط افزودن ربات تلگرام جدید"
echo "  3) فقط وب مشترک کد ۵ رقمی (مثلاً bale.cyou)"
echo "  4) فقط زیرساخت (Traefik + DB) بدون ربات"
echo "  5) نمایش وضعیت"
echo "  q) خروج"
echo ""

choice="$(prompt "انتخاب" "2")"

case "$choice" in
  1)
    ensure_traefik
    ensure_shared_db
    PICKUP_DOMAIN="$(prompt "دامنه وب کد ۵ رقمی" "${PICKUP_DOMAIN:-bale.cyou}")"
    provision_pickup_site "$PICKUP_DOMAIN"
    save_cluster
    bot_domain="$(prompt "دامنه ربات (مثلاً shop.example.com)" "")"
    [ -n "$bot_domain" ] && provision_bot_instance "$bot_domain"
    save_cluster
    ;;
  2)
    ensure_traefik
    ensure_shared_db
    if [ "${INFRA_PICKUP:-0}" != "1" ] && ! [ -f "$INSTANCES_DIR/${PICKUP_DOMAIN:-bale.cyou}/.env" ]; then
      warn "وب pickup هنوز نیست — پیشنهاد: گزینه 3 را یک‌بار اجرا کنید"
      if [ "$(prompt "الان pickup را نصب کنم؟ (y/N)" "y")" = "y" ]; then
        provision_pickup_site "${PICKUP_DOMAIN:-bale.cyou}"
      fi
    fi
    save_cluster
    bot_domain="$(prompt "دامنه ربات جدید" "")"
    provision_bot_instance "$bot_domain"
    save_cluster
    ;;
  3)
    ensure_traefik
    ensure_shared_db
    save_cluster
    pickup_domain="$(prompt "دامنه pickup" "${PICKUP_DOMAIN:-bale.cyou}")"
    provision_pickup_site "$pickup_domain"
    save_cluster
    ;;
  4)
    ensure_traefik
    ensure_shared_db
    save_cluster
    ok "زیرساخت آماده — برای ربات گزینه 2 را بزنید"
    ;;
  5)
    show_status
    exit 0
    ;;
  q|Q)
    exit 0
    ;;
  *)
    err "گزینه نامعتبر"
    exit 1
    ;;
esac

save_cluster
show_status
echo ""
ok "تمام شد."
